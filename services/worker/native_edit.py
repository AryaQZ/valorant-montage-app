DRUM_COLUMNS = {"low": (1, 0.50), "mid": (2, 0.60)}


def regular_drum_runs(rows, attacks, count, bpm, duration, earliest_drop, preferred_drop):
    """Find one strong, recurring attack per independent kill in an untouched song."""
    if count < 2:
        return []
    strengths = {row[0]: row for row in rows}
    period = 60 / bpm
    candidates = []
    for start in strengths:
        if not float(start).is_integer():
            continue
        for step in (1, 2, 4, 6, 8):
            spacing = step * period
            if not 0.98 <= spacing <= 3.0:
                continue
            positions = [start + i * step for i in range(count)]
            for band, (column, threshold) in DRUM_COLUMNS.items():
                if not all(band in attacks.get(position, {}) and strengths[position][column] >= threshold
                           for position in positions):
                    continue
                times = [attacks[position][band] for position in positions]
                if times[0] < earliest_drop or times[-1] + 2.5 > duration:
                    continue
                drift = max(abs((b - a) - spacing) for a, b in zip(times, times[1:]))
                if drift > 0.05:
                    continue
                values = [strengths[position][column] for position in positions]
                # Recurrence and audible strength outrank proximity to the estimated drop.
                score = (2 * min(values) + sum(values) / count - 9 * drift
                         - 0.75 * abs(spacing - 1.40) - 0.006 * abs(times[0] - preferred_drop))
                candidates.append((score, {"drop_beat": int(start), "step": step,
                                          "attack_us": [round(t * 1e6) for t in times],
                                          "drum": "snare" if band == "mid" else "kick"}))
    return [row for _, row in sorted(candidates, key=lambda pair: pair[0], reverse=True)]


def _measure_candidates(plan_path, output_path):
    import beat_hits

    plan = json.loads(Path(plan_path).read_text(encoding="utf-8"))
    bpm, beat0 = plan["bpm"], plan["beat0"]
    song = beat_hits.decode(plan["music"])
    duration = len(song) / beat_hits.SR
    earliest_drop = plan["earliest_drop"]
    preferred = beat0 + plan["drop_beat"] * 60 / bpm
    lo = max(0, int((earliest_drop - beat0) * bpm / 60) - 1)
    hi = min((duration - beat0) * bpm / 60, lo + max(180, plan["count"] * 8 + 8) * bpm / 60)
    if hi <= lo:
        _write(output_path, [])
        return
    rows, measured = beat_hits.measure_t(song, bpm, beat0, 0, lo, hi, raw=True)
    candidates = regular_drum_runs(rows, measured.bands, plan["count"], bpm, duration,
                                  earliest_drop, preferred)
    _write(output_path, candidates[:8])


def _write(path, data):
    Path(path).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def entry_transition(motion, prefer_roll, previous, index):
    """Keep steady setups clear and follow motion on faster entries."""
    if motion < 3.5:
        return "cut", 0.0
    sign = 1 if index % 2 else -1
    if motion >= 8 and prefer_roll and previous != "broll":
        return "broll", 0.0, sign
    if previous == "bwhip":
        return "cut", 0.0
    return "bwhip", 0.0, sign


def _tune(config_path):
    import clipio
    import cv2
    import numpy as np
    import timeline

    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    previous = "fade"
    transitions = []
    for index, take in enumerate(timeline.SEGS[1:], start=1):
        start = int(np.floor(take["a"][0][1]))
        stop = min(clipio.n_frames(take["clip"]) - 1, start + 4)
        if stop <= start:
            transition = ("cut", 0.0)
        else:
            pictures = clipio.read_frames(take["clip"], start, stop, crop=False)
            gray = np.stack([cv2.resize(cv2.cvtColor(p, cv2.COLOR_RGB2GRAY), (160, 90),
                                        interpolation=cv2.INTER_AREA)[14:69, 20:140] for p in pictures])
            motion = float(np.abs(np.diff(gray.astype(np.float32), axis=0)).mean())
            transition = entry_transition(motion, config["prefer_roll"], previous, index)
        if config.get("keep_final_action_clear") and index == len(timeline.SEGS) - 1:
            transition = ("cut", 0.0)
        transitions.append((index, transition))
        previous = transition[0]
    # Only built-in values generated by the worker become executable timeline settings.
    with Path("timeline.py").open("a", encoding="utf-8") as file:
        file.write("\n# Studio context-sensitive joins and audio mix\n")
        for index, transition in transitions:
            file.write(f"SEGS[{index}]['tin'] = {transition!r}\n")
        for key in ("GAME_LEVEL", "HEADROOM", "KILL_THUMP"):
            file.write(f"{key} = {config[key]!r}\n")
        if config["look"]["kill_zoom"] == 0:
            file.write("IMPACT = None\n")




def _preserve_final_action(config_path, output_path):
    import importlib
    import math
    import clipio
    import timeline as t

    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    take = t.SEGS[-1]
    alias = take["clip"]
    first_beat = take["kills"][0][0]
    impact = float(take["map"](take["kills"][-1][0])[0])
    first_impact = float(take["map"](first_beat)[0])
    ingest = json.loads(Path("src/ingest.json").read_text(encoding="utf-8"))[alias]
    origin = ingest.get("t0", 0.0)
    requested = config["source_time_us"]
    source_frame = (max(3, impact - 72) if requested is None else
                    float(clipio.t2n(alias, requested / 1e6 - origin)))
    if not 0 <= source_frame < impact:
        raise ValueError("Titik awal aksi harus berada sebelum kill terakhir di rekaman yang sama.")
    if source_frame < float(take["a"][0][1]) - 1e-6:
        # Choose a real beat subdivision early enough to show the whole lead-in at 1x.
        latest = t.nearest_frame(first_beat) - math.ceil(first_impact - source_frame - 1e-6)
        previous = t.SEGS[-2]
        previous_end = t.nearest_frame(previous["kills"][-1][0]) if previous["kills"] else t.nearest_frame(previous["r0"])
        required_tail = t.E[-2][-1].get("upto") or 8
        cut = math.floor(t.frame_beat(latest) * 8) / 8
        cut_frame = t.nearest_frame(t.vis(cut, t.CUT_LEAD))
        if t.E[-1][0] not in ("K", "M") or cut_frame - previous_end < required_tail + 2:
            raise ValueError("Beat sebelum kill terakhir terlalu rapat untuk menjaga ancang-ancang dan hasil kill sebelumnya.")
        lead_beats = take["hits"][0] - cut
        timeline = Path("timeline.py")
        data = timeline.read_text(encoding="utf-8")
        marker = "\nSEGS = []\n"
        if data.count(marker) != 1:
            raise ValueError("Draft tidak mendukung pemetaan ulang awal aksi.")
        options = f"\nE[-1][-1].update(lb={lead_beats!r}, n=None)\n"
        if "end" in t.E[-2][-1]:
            options += f"E[-2][-1]['end'] = {cut!r}\n"
        timeline.write_text(data.replace(marker, options + marker, 1), encoding="utf-8")
        t = importlib.reload(t)
        take = t.SEGS[-1]
    begin = t.nearest_frame(take["r0"])
    finish = t.nearest_frame(take["kills"][-1][0])
    if float(take["map"](t.frame_beat(begin))[0]) > source_frame + 0.1:
        raise ValueError("Draft masih memotong awal aksi yang ditandai.")
    action = next(n for n in range(begin, finish + 1)
                  if float(take["map"](t.frame_beat(n))[0]) >= source_frame - 0.1)
    _write(output_path, {"source_alias": alias, "source_time_us": round((float(clipio.n2t(alias, source_frame)) + origin) * 1e6),
                         "start_frame": begin, "action_frame": action, "shot_frame": finish})


def _audit_final_action(video_path, config_path, output_path):
    import clipio
    import cv2
    import numpy as np
    import timeline as t

    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    lo, hi = config["action_frame"], config["shot_frame"]
    take = t.SEGS[-1]
    checks = []
    cap = cv2.VideoCapture(video_path)

    def center(gray):
        return cv2.resize(gray, (160, 90), interpolation=cv2.INTER_AREA)[19:70, 28:132]

    try:
        for n in sorted({lo, (lo + hi) // 2, max(lo, hi - 2), hi}):
            cap.set(cv2.CAP_PROP_POS_FRAMES, n)
            ok, picture = cap.read()
            if not ok:
                break
            source_n = round(float(take["map"](t.frame_beat(n))[0]))
            source = clipio.read_frames(take["clip"], source_n, source_n, crop=False)[0]
            left = center(cv2.cvtColor(source, cv2.COLOR_RGB2GRAY))
            right = center(cv2.cvtColor(picture, cv2.COLOR_BGR2GRAY))
            score = float(cv2.matchTemplate(right, left, cv2.TM_CCOEFF_NORMED)[0, 0])
            checks.append({"output_frame": n, "source_frame": source_n, "correlation": round(score, 3)})
    finally:
        cap.release()
    expected = len({lo, (lo + hi) // 2, max(lo, hi - 2), hi})
    _write(output_path, {"verified": len(checks) == expected and all(check["correlation"] >= 0.7 for check in checks),
                         "context_frames": hi - lo, "matches": checks})


def _preserve_ace(config_path, output_path):
    import math
    import clipio
    import timeline as t

    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    take = t.SEGS[-1]
    shot, _ = take["kills"][-1]
    alias = take["clip"]
    ingest = json.loads(Path("src/ingest.json").read_text(encoding="utf-8"))[alias]
    source_time = config["source_time_us"] / 1e6 - ingest.get("t0", 0.0)
    source = float(clipio.t2n(alias, source_time))
    impact = float(take["map"](shot)[0])
    distance = source - impact
    if distance <= 0 or source + 3 >= clipio.n_frames(alias):
        raise ValueError("Titik ACE harus berada setelah kill terakhir dan punya footage sesudahnya.")
    # Leave room for the cubic to ease out of the 1x impact without overshoot.
    cue_n = t.nearest_frame(shot) + max(6, math.ceil(distance / 0.60))
    fade_n = t.nearest_frame(t.LUMA_FADE[0])
    if fade_n - cue_n < 24:
        raise ValueError("Draft terlalu pendek untuk mempertahankan tampilan ACE sebelum fade.")
    cue = t.frame_beat(cue_n)
    tail = take["r1"]
    remaining_frames = (tail - cue) * t.FPB
    rate = min(0.20, (clipio.n_frames(alias) - 2 - source) / remaining_frames)
    prefix = [tuple(a) for a in take["a"] if a[0] < shot - 1e-8]
    anchors = prefix + [(shot, impact, 1.0), (cue, source, rate),
                        (tail, source + rate * remaining_frames, rate)]
    with Path("timeline.py").open("a", encoding="utf-8") as stream:
        stream.write(f"\n# Keep the reviewed ACE banner in the final take.\n"
                     f"SEGS[-1]['a'] = {anchors!r}\n"
                     "SEGS[-1]['map'] = TimeMap(SEGS[-1]['a'])\n")
    _write(output_path, {**config, "source_alias": alias, "output_frame": cue_n,
                         "frames_before_fade": fade_n - cue_n})


def _native_pre_shot_frames(picture):
    import clipio
    import cv2
    import ingest
    import numpy as np
    import subprocess

    manifest = json.loads(Path("src/ingest.json").read_text(encoding="utf-8"))
    origins = {}
    protection = {}

    def luma(rgb):
        gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
        return cv2.resize(gray, (192, 108), interpolation=cv2.INTER_AREA).astype(np.float32)

    for take, frames in zip(picture.SEGS, picture.KILLF):
        alias = take["clip"]
        record = manifest.get(alias, {})
        if record.get("method") != "exact":
            continue
        path = record["original"]
        if alias not in origins:
            video, _ = ingest.probe(path)
            if not video:
                continue
            pts = ingest.packet_pts(path, video["index"])
            filters, _, _ = ingest.decode_filter(
                video, record.get("aspect", "pad"), video.get("color_transfer") in ingest.HDR_TRC)
            origins[alias] = video["index"], pts, filters
        stream, pts, filters = origins[alias]
        for (beat, _), frame in zip(take["kills"], frames):
            shot = int(round(float(take["map"](beat)[0])))
            if shot < 1 or frame < 1:
                continue
            target = record.get("t0", 0.0) + float(clipio.n2t(alias, shot - 1))
            index = int(np.searchsorted(pts, target + 0.0005, side="right")) - 1
            if index < 0 or not 0.0015 < target - pts[index] < 0.05:
                continue
            instant = float(pts[index])
            window = min(0.002, (pts[index + 1] - instant) / 3) if index + 1 < len(pts) else 0.002
            select = f"select='between(t\\,{instant - window:.6f}\\,{instant + window:.6f})'"
            result = subprocess.run([picture.FF, "-v", "error", "-copyts", "-ss",
                                     f"{max(0, instant - 1):.6f}", "-i", path, "-map", f"0:{stream}",
                                     "-vf", select + "," + filters, "-frames:v", "1", "-an",
                                     "-pix_fmt", "rgb24", "-c:v", "rawvideo", "-threads:v", "1",
                                     "-f", "rawvideo", "pipe:1"], capture_output=True, timeout=30)
            if result.returncode or len(result.stdout) != picture.SRC_W * picture.SRC_H * 3:
                print(f"Native pre-shot frame unavailable for {alias}@{shot}", flush=True)
                continue
            original = np.frombuffer(result.stdout, np.uint8).reshape(picture.SRC_H, picture.SRC_W, 3)
            previous, current = map(luma, clipio.read_frames(alias, shot - 1, shot, crop=False))
            native = luma(original)
            flash = np.maximum(current - previous, 0).ravel()
            early = np.maximum(previous - native, 0).ravel()
            if flash.std() <= 1 or early.std() <= 1:
                continue
            if float(np.corrcoef(flash, early)[0, 1]) >= 0.44:
                protection[frame] = original
    return protection


def _render(output):
    import render as picture

    # A straight cut also removes the outgoing two-frame zoom/colour split.
    direct_entries = {picture.CUTF[i] for i, take in enumerate(picture.SEGS)
                      if i and take["tin"][0] == "cut"}
    before_direct = {entry - step for entry in direct_entries for step in (1, 2)}
    settings = picture.KZ, picture.FRG
    picture.cv2.setNumThreads(4)
    store = picture.Store()
    sample = store.sample
    cam, look = picture.cam, picture.look
    burst, rays = picture.impact_burst, picture.impact_rays
    protected = _native_pre_shot_frames(picture)
    protected_window = {frame + relative: relative for frame in protected for relative in range(-2, 4)}
    print(f"Original pre-impact frames used at: {sorted(protected)}", flush=True)
    frame = -1

    def real_source_sample(clip, left, right):
        if frame + 1 in protected:
            return picture.LIN[protected[frame + 1]]
        return sample(clip, left, right)

    def camera(take, number):
        if number in protected_window:
            return (*picture.SEGS[take]["view"], 0)
        return cam(take, number)

    def exposure(take, number):
        if number in protected_window:
            strength = picture.LK["flash"] / 0.55
            amount = {0: 0.22, 1: 0.1, 2: 0.05, 3: 0.02}.get(protected_window[number], 0)
            return 1 + strength * amount, picture.CA0
        return look(take, number)

    store.sample = real_source_sample
    picture.cam = camera
    picture.look = exposure
    picture.impact_burst = lambda img, i, n: img if n in protected_window else burst(img, i, n)
    picture.impact_rays = lambda img, i, n: (img, False) if n in protected_window else rays(img, i, n)

    encoder = picture.encoder(output)
    try:
        with encoder.stdin:
            for frame in range(picture.T.N_FRAMES):
                index = picture.T.take_of(frame)
                take = picture.SEGS[index]
                normal_shutter = take["shutter"]
                recent_impact = max((hit for hit in picture.KILLF[index] if hit <= frame), default=frame)
                speed = float(take["map"](picture.T.frame_beat(frame))[1])
                if frame - recent_impact > 8 and speed < 0.65:
                    # Wider shutter through the slowed recoil spreads isolated
                    # motion across samples without delaying a fatal frame.
                    take["shutter"] = max(normal_shutter, 1.22)
                picture.KZ, picture.FRG = (0.0, 0.0) if frame in before_direct else settings
                try:
                    rgb = picture.render_frame(frame, store)
                finally:
                    take["shutter"] = normal_shutter
                encoder.stdin.write(rgb.tobytes())
                if frame % 100 == 0:
                    print(f"Frame {frame}/{picture.T.N_FRAMES}", flush=True)
    finally:
        result = encoder.wait()
    if result:
        raise RuntimeError(f"FFmpeg picture encode exited with code {result}")


def _inspect_attacks(output_path):
    import beat_hits
    import timeline as t

    song = beat_hits.decode(t.MUSIC)
    rows, measured = beat_hits.measure_t(song, t.BPM, t.BEAT0, t.M0, t.R0, t.R1, raw=True, sub=4)
    hits = [
        (time, "kick" if band == "low" else "snare" if band == "mid" else "hat", row[column])
        for row in rows
        for band, column in (("low", 1), ("mid", 2), ("high", 3))
        if row[column] > 0
        for time in [measured.bands.get(row[0], {}).get(band)]
        if time is not None
    ]
    actual = []
    for take in t.SEGS:
        for beat in take["hits"]:
            at = t.beat_time(beat)
            closest = min(hits, key=lambda hit: abs(hit[0] - at), default=None)
            if closest is None or abs(closest[0] - at) > 0.004:
                actual.append(None)
            else:
                ts, kind, strength = closest
                actual.append({"kind": kind, "strength": strength, "song_time_us": round(ts * 1e6)})
    _write(output_path, actual)


def _mix(config_path):
    import audio as a
    import clipio
    import numpy as np
    from scipy.ndimage import median_filter
    from scipy.signal import butter, istft, sosfiltfilt, stft

    config = json.loads(Path(config_path).read_text(encoding="utf-8"))

    def band(x, lo, hi):
        return sosfiltfilt(butter(3, [lo, hi], btype="bandpass", fs=a.SR, output="sos"), x, axis=0)

    def rms(x):
        return float(np.sqrt(np.mean(x * x)))

    def confirmation(x):
        _, _, spectrum = stft(x.T, fs=a.SR, nperseg=1024, noverlap=768)
        magnitude = np.abs(spectrum).mean(axis=0)
        floor = median_filter(magnitude, size=(13, 1), mode="nearest")
        support = np.clip(1 - 1.6 * floor / (magnitude + 1e-8), 0, 1)
        _, result = istft(spectrum * (0.43 + 0.57 * support)[None, :, :], fs=a.SR,
                          nperseg=1024, noverlap=768)
        return result.T[:len(x)]

    music = a.music()                          # native playback and upstream fades
    decode = a.decode
    cached = {}

    def decode_once(path):
        if path not in cached:
            cached[path] = decode(path)
        return cached[path]

    a.decode = decode_once
    try:
        game, records = a.game()
    finally:
        a.decode = decode
    effects = a.sfx()
    cue_bus = np.zeros_like(game)
    duck = np.zeros(a.NS, dtype=np.float32)
    for index, record in enumerate(records):
        # The bed remains at full level on the attack. When another hit follows
        # soon, shorten the tail so the next kill and its beat stay audible.
        record["confirmation"] = None
        if record["onset_ms"] is None or a.T.GAME_LEVEL == 0:
            continue
        hit = record["hit"]
        next_hit = records[index + 1]["hit"] if index + 1 < len(records) else a.NS
        start = round(0.070 * a.SR)
        stop = min(round(0.42 * a.SR), next_hit - hit - round(0.07 * a.SR), a.NS - hit)
        if stop - start < round(0.09 * a.SR):
            continue
        base = round((record["t0"] + record["onset_ms"] / 1000) * a.SR)
        if base + start < 0:
            continue
        source = cached.get(clipio.path(record["clip"]))
        if source is None:
            continue
        stop = min(stop, len(source) - base)
        if stop - start < round(0.09 * a.SR):
            continue
        sample = source[base + start:base + stop]
        clean_tail = confirmation(band(sample.astype(np.float64), 280, 2450))
        time = np.arange(len(clean_tail)) / a.SR
        fade = a.smooth(time / 0.035) * a.smooth((len(time) / a.SR - time) / 0.095)
        cue = clean_tail * fade[:, None]
        if rms(cue) < 0.001:
            continue
        gain = min(6.5, 0.047 / rms(cue), 0.22 / float(np.abs(cue).max()))
        cue_bus[hit + start:hit + stop] += cue * gain
        begin, end = hit + round(0.045 * a.SR), min(a.NS, next_hit, hit + stop + round(0.08 * a.SR))
        u = np.arange(end - begin) / a.SR
        envelope = a.smooth(u / 0.05) * a.smooth(((end - begin) / a.SR - u) / 0.11)
        duck[begin:end] = np.maximum(duck[begin:end], envelope)
        record["confirmation"] = {"start_sample": hit + start, "end_sample": hit + stop,
                                  "gain": round(gain, 3), "source": "post-shot gameplay"}
    cached.clear()
    music = (music * (1 - (1 - 10 ** (-2.7 / 20)) * duck[:, None])
             - (1 - 10 ** (-1.2 / 20)) * duck[:, None] * band(music, 420, 1900))
    mix = (config["music_level"] * music + a.T.GAME_LEVEL * (game + cue_bus) + effects) * a.HEADROOM
    peak = float(np.abs(mix).max())
    if not np.isfinite(mix).all() or peak > 1:
        raise ValueError(f"Studio mix peak {peak:.3f} exceeds the pre-master sample range")
    with wave.open("mix.wav", "wb") as wav:
        wav.setnchannels(2)
        wav.setsampwidth(2)
        wav.setframerate(a.SR)
        wav.writeframes(np.round(mix * 32767).astype("<i2").tobytes())
    keys = ("beat", "shown", "clip", "state", "how", "onset_ms", "placed_ms", "confirmation")
    kills = [{**{key: record[key] for key in keys}, "hit_sample": record["hit"],
              "rise_db": record.get("rise")} for record in records]
    _write("audio_report.json", {"timeline": hashlib.sha1(Path("timeline.py").read_bytes()).hexdigest(),
                                 "style": "reference", "sync": 2, "samples": a.NS,
                                 "written_peak": peak, "music_speed": 1.0,
                                 "confirmation_layers": sum(r["confirmation"] is not None for r in records),
                                 "kills": kills})


